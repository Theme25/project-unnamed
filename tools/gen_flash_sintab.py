#!/usr/bin/env python3
"""Emit src/flash_sintab.h: Flash Player's fixed-point sine table.

Flash Player 11.4 (SAFlashPlayer.exe 11.4.402.287, table at 0x00ae1e98) stores
trunc(sin(i * 0.25 deg) * 2^31) as uint32; this formula reproduces entries 0..361
(the only ones the sine routine can read) bit for bit."""
import math
vals = [math.trunc(math.sin(i * 0.25 * (math.pi / 180)) * (1 << 31)) for i in range(362)]
print("// Generated by tools/gen_flash_sintab.py -- do not edit.")
print("// Flash Player 11.4 fixed-point sine table: trunc(sin(i * 0.25 deg) * 2^31), i = 0..361")
print("// (identical to the player's own table, SAFlashPlayer.exe 11.4.402.287 @ 0x00ae1e98).")
print("#pragma once\n#include <cstdint>\nnamespace rb {\nstatic const uint32_t kFlashSinTab[362] = {")
for i in range(0, 362, 6):
    print("    " + ", ".join(str(v) + "u" for v in vals[i:i + 6]) + ",")
print("};\n}  // namespace rb")
